"""Object storage for original files and page images.

Keys are generated by Mentis (tenant/version/uuid), never derived from user input.
"""

import io
from functools import lru_cache
from typing import Protocol

from app.core.config import get_settings


class Storage(Protocol):
    def put(self, key: str, data: bytes, content_type: str) -> None: ...
    def get(self, key: str) -> bytes: ...
    def delete_prefix(self, prefix: str) -> None: ...
    def ping(self) -> bool: ...


class MinioStorage:
    def __init__(self) -> None:
        from minio import Minio

        s = get_settings()
        self.bucket = s.minio_bucket
        self.client = Minio(s.minio_endpoint, access_key=s.minio_access_key, secret_key=s.minio_secret_key, secure=s.minio_secure)
        self._ready = False

    def _ensure_bucket(self) -> None:
        if not self._ready:
            if not self.client.bucket_exists(self.bucket):
                self.client.make_bucket(self.bucket)
            self._ready = True

    def put(self, key: str, data: bytes, content_type: str) -> None:
        self._ensure_bucket()
        self.client.put_object(self.bucket, key, io.BytesIO(data), len(data), content_type=content_type)

    def get(self, key: str) -> bytes:
        resp = self.client.get_object(self.bucket, key)
        try:
            return resp.read()
        finally:
            resp.close()
            resp.release_conn()

    def delete_prefix(self, prefix: str) -> None:
        self._ensure_bucket()
        for obj in self.client.list_objects(self.bucket, prefix=prefix, recursive=True):
            self.client.remove_object(self.bucket, obj.object_name)

    def ping(self) -> bool:
        try:
            self._ensure_bucket()
            return True
        except Exception:  # noqa: BLE001 - any failure means storage is not usable
            return False


class MemoryStorage:
    """In-process storage for tests."""

    def __init__(self) -> None:
        self.objects: dict[str, bytes] = {}

    def put(self, key: str, data: bytes, content_type: str) -> None:
        self.objects[key] = data

    def get(self, key: str) -> bytes:
        return self.objects[key]

    def delete_prefix(self, prefix: str) -> None:
        for k in [k for k in self.objects if k.startswith(prefix)]:
            del self.objects[k]

    def ping(self) -> bool:
        return True


_override: Storage | None = None


def set_storage(storage: Storage | None) -> None:
    global _override
    _override = storage


@lru_cache
def _default() -> Storage:
    return MinioStorage()


def get_storage() -> Storage:
    return _override or _default()


def original_key(tenant_id, version_id, file_type: str) -> str:
    return f"tenants/{tenant_id}/versions/{version_id}/original.{file_type}"


def page_image_key(tenant_id, version_id, index: int) -> str:
    return f"tenants/{tenant_id}/versions/{version_id}/pages/{index:04d}.png"


def version_prefix(tenant_id, version_id) -> str:
    return f"tenants/{tenant_id}/versions/{version_id}/"


def tenant_prefix(tenant_id) -> str:
    return f"tenants/{tenant_id}/"
